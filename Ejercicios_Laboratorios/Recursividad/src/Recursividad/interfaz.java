     static int suma(int[] v, int i){
    if (i == 0){
   
        return v[0];
   
    } else {
    return suma(v, i -1) + v[i];
           
    }
    } 
     
     
     
     public int calcular_factorial(int numero) {
  
        if (numero == 0 ||numero == 1) {
            return 1;
        } else {
            return numero * calcular_factorial(numero - 1);
        }
    }

     
     
    public int calcular_potencia(int base, int exponente) {
 
        if (exponente == 0) {
            return 1;
        } else {
            return base * calcular_potencia(base, exponente - 1);
        }
    }

    public static int sumaGauss(int n) {
    if (n <= 0) {
        return 0;
    }
    return n + sumaGauss(n - 1);
}
     
     
     
     
     
